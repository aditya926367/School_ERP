const currencyPercent = (marks: number, total: number) =>
  total > 0 ? Math.round((marks / total) * 10000) / 100 : 0;

const formatDate = (date: string) =>
  new Date(`${date}T00:00:00`).toLocaleDateString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  });

function getSummary(result: ExamResult) {
  const obtained = result.subjects.reduce((sum, subject) => sum + subject.marks, 0);
  const maximum = result.subjects.reduce((sum, subject) => sum + subject.total, 0);
  const percentage = currencyPercent(obtained, maximum);

  return {
    obtained,
    maximum,
    percentage,
    grade: percentage >= 90 ? "A+" : percentage >= 80 ? "A" : percentage >= 70 ? "B+" : percentage >= 60 ? "B" : "C",
  };
}

function exportReport(result: ExamResult) {
  const summary = getSummary(result);
  const lines = [
    "School ERP - Academic Report",
    `Student: ${result.student}`,
    `Class: ${result.className}`,
    `Examination: ${result.exam}`,
    `Result Date: ${formatDate(result.date)}`,
    "",
    "Subject,Marks Obtained,Maximum Marks,Grade,Remarks",
    ...result.subjects.map((subject) =>
      [subject.subject, subject.marks, subject.total, subject.grade, subject.remarks]
        .map((value) => `"${String(value).replace(/"/g, '""')}"`)
        .join(","),
    ),
    "",
    `Total Marks,${summary.obtained}`,
    `Maximum Marks,${summary.maximum}`,
    `Percentage,${summary.percentage}%`,
    `Overall Grade,${summary.grade}`,
    "",
    "Demo report generated by the School ERP frontend.",
  ];

  const blob = new Blob(["\uFEFF" + lines.join("\n")], {
    type: "text/csv;charset=utf-8;",
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${result.student.replace(/\s+/g, "-")}-${result.exam.replace(/\s+/g, "-")}-results.csv`;
  link.click();
  URL.revokeObjectURL(url);
}

